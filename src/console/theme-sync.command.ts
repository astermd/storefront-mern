import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Command, CommandRunner, Option } from 'nest-commander';
import { BuiltCatalog, CatalogBuilder } from '../catalog/catalog-builder';
import { CatalogValidator } from '../catalog/catalog-validator';
import { GeneratedConfigWriter } from '../catalog/generated-config-writer';
import { MediaLocalizer } from '../catalog/media-localizer';
import { EmrClientFactory } from '../emr/client-factory';
import { ConfigService } from '../support/config';

interface ThemeSyncOptions {
  apply?: boolean;
  channel?: string;
  currency?: string;
}

/**
 * Ported from storefront-lamp/core/Console/SyncCommand.php. `theme:sync` — the centerpiece of the
 * catalog pipeline. Fetches the configured EMR channel's detail record, runs it through
 * `CatalogBuilder`, and (in `--apply` mode only) localizes remote product images via
 * `MediaLocalizer` before writing two generated files:
 *
 * - `config/products.generated.ts` — the full built catalog. Overwritten wholesale on every sync;
 *   hand customisations belong in `config/products.overrides.ts`, which this command never
 *   touches. `config/products.generated.example.ts` is the permanent, never-overwritten shape
 *   reference this file started from.
 * - `config/channel.generated.ts` — the channel id/name and payment-processor block, merged onto
 *   whatever is already there (`GeneratedConfigWriter.mergeOntoExisting`) — a hand-added key
 *   survives a re-sync of the same channel, except `payment_processor` (always replaced wholesale)
 *   and the whole file (replaced wholesale) when `channel.id` changes.
 *
 * **Rebuild after `--apply`.** Both generated files are TypeScript source modules, resolved at
 * `nest build` time — a sync takes effect once the app is rebuilt and restarted, not on the next
 * request the way PHP's `require` re-read the file every time.
 *
 * Defaults to a dry run: no writes, no media localization, just the counts an operator needs to
 * decide whether to `--apply` (remote images that would be localized, variants still missing a
 * provider mapping). `--apply` performs the writes, runs media localization, and then runs
 * `CatalogValidator` against the result — exit code 2 on a validation error, matching the PHP
 * original exactly (not 1).
 */
@Command({ name: 'theme:sync', description: 'Sync the generated catalog and channel config from the configured EMR channel' })
export class ThemeSyncCommand extends CommandRunner {
  constructor(
    private readonly clients: EmrClientFactory,
    private readonly config: ConfigService,
  ) {
    super();
  }

  @Option({ flags: '--apply', description: 'Write the generated files (default is a dry run that only prints diffs)' })
  parseApply(): boolean {
    return true;
  }

  @Option({ flags: '--channel <id>', description: 'Channel ID to sync (overrides app.emr.channel_id)' })
  parseChannel(value: string): string {
    return value;
  }

  @Option({ flags: '--currency <code>', description: 'Currency code stamped onto the generated catalog' })
  parseCurrency(value: string): string {
    return value;
  }

  async run(_params: string[], options: ThemeSyncOptions): Promise<void> {
    const channelId = this.resolveChannelId(options);
    if (channelId === null) {
      console.error('theme:sync: no channel id — pass --channel or set app.emr.channel_id (ASTERMD_CHANNEL_ID).');
      process.exitCode = 1;
      return;
    }

    let data: Record<string, unknown>;
    try {
      const client = this.clients.create();
      const response = await client.channels().details(channelId);
      data = response.data() as Record<string, unknown>;
    } catch (error) {
      console.error(`theme:sync: failed to fetch channel details: ${error instanceof Error ? error.message : String(error)}`);
      process.exitCode = 1;
      return;
    }

    const currency = options.currency ?? 'USD';
    let catalog = CatalogBuilder.build(data, currency);
    // Computed on the built (pre-localization) catalog: media localization only rewrites
    // image/gallery fields, never variants, so this count is identical whether taken before or
    // after localize() — computing it here keeps dry-run and apply reporting on the same basis.
    const missingProviders = ThemeSyncCommand.countMissingProviders(catalog);

    const configDir = join(process.cwd(), 'config');
    const mediaDir = join(process.cwd(), 'public/assets/media');
    const productsFile = join(configDir, 'products.generated.ts');
    const channelFile = join(configDir, 'channel.generated.ts');

    const productsHeader = `GENERATED by npm run console -- theme:sync --apply — do not hand-edit.\nOverrides belong in config/products.overrides.ts (they survive every sync).\nChannel: ${String(data._id ?? '')} (${String(data.name ?? '')})`;
    const channelHeader =
      'GENERATED by npm run console -- theme:sync --apply — do not hand-edit.\n' +
      'Hand-added keys outside payment_processor survive a re-sync of the same channel.\n' +
      'payment_processor is replaced every sync, and a different channel replaces this file.';

    const channelPayload = GeneratedConfigWriter.channelPayload(data);
    const existingChannelPayload = GeneratedConfigWriter.readExistingChannelPayload();
    const mergedChannelPayload = GeneratedConfigWriter.mergeOntoExisting(existingChannelPayload, channelPayload);

    if (options.apply !== true) {
      console.log(`products.generated.ts would ${existsSync(productsFile) ? 'change' : 'be created'} — ${Object.keys(catalog.products).length} products.`);
      console.log(`channel.generated.ts would ${existsSync(channelFile) ? 'change' : 'be created'}.`);
      console.log(`media: ${ThemeSyncCommand.countRemoteImages(catalog)} images would be localised`);
      ThemeSyncCommand.reportMissingProviders(missingProviders);
      return;
    }

    const localizer = new MediaLocalizer(mediaDir, this.clients.create().assetUrl('ui/'));
    const localized = await localizer.localize(catalog);
    catalog = localized.catalog;
    ThemeSyncCommand.printMediaReport(localized.report);
    ThemeSyncCommand.reportMissingProviders(missingProviders);

    if (!existsSync(configDir)) mkdirSync(configDir, { recursive: true });
    writeFileSync(productsFile, GeneratedConfigWriter.renderProductsModule(catalog, productsHeader));
    writeFileSync(channelFile, GeneratedConfigWriter.renderChannelModule(mergedChannelPayload, channelHeader));

    const result = new CatalogValidator().validate(catalog);
    for (const warning of result.warnings) console.log(`validation warning: ${warning}`);

    if (result.errors.length > 0) {
      for (const error of result.errors) console.error(`validation error: ${error}`);
      process.exitCode = 2;
    }
  }

  private resolveChannelId(options: ThemeSyncOptions): string | null {
    if (options.channel) return options.channel;

    try {
      return this.clients.channelId();
    } catch {
      return null;
    }
  }

  private static printMediaReport(report: { downloaded: number; unchanged: number; failed: string[]; orphaned: string[] }): void {
    console.log(`media: ${report.downloaded} downloaded, ${report.unchanged} unchanged, ${report.failed.length} failed, ${report.orphaned.length} orphaned`);
    if (report.failed.length > 0) console.log(`media: failed slugs — ${report.failed.join(', ')}`);
  }

  private static reportMissingProviders(missingProviders: number): void {
    console.log(`${missingProviders > 0 ? 'warning: ' : ''}${missingProviders} variants lack provider identifiers`);
  }

  private static countRemoteImages(catalog: BuiltCatalog): number {
    return Object.values(catalog.products).filter((product) => (product.remote_image ?? null) !== null).length;
  }

  private static countMissingProviders(catalog: BuiltCatalog): number {
    let count = 0;
    for (const product of Object.values(catalog.products)) {
      for (const variant of product.variants ?? []) {
        if ((variant.provider ?? null) === null) count += 1;
      }
    }
    return count;
  }
}
